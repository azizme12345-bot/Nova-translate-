function escapeHtml(str) {
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/"/g, '&quot;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

export function buildPairPageHtml(baseHtml, routePath) {
  const cfg = PAIR_PAGES[routePath];
  if (!cfg) return baseHtml;

  const t = escapeHtml(cfg.title);
  const d = escapeHtml(cfg.description);
  const canonical = `${SITE_URL}${cfg.path}`;

  let html = baseHtml;
  html = html.replace(/<title>[\s\S]*?<\/title>/, () => `<title>${t}</title>`);
  html = html.replace(/(<meta name="description" content=")[^"]*(")/, (_, a, b) => a + d + b);
  html = html.replace(/(<link rel="canonical" href=")[^"]*(")/, (_, a, b) => a + canonical + b);
  html = html.replace(/(<meta property="og:title" content=")[^"]*(")/, (_, a, b) => a + t + b);
  html = html.replace(/(<meta property="og:description" content=")[^"]*(")/, (_, a, b) => a + d + b);
  html = html.replace(/(<meta property="og:url" content=")[^"]*(")/, (_, a, b) => a + canonical + b);
  html = html.replace(/(<meta name="twitter:title" content=")[^"]*(")/, (_, a, b) => a + t + b);
  html = html.replace(/(<meta name="twitter:description" content=")[^"]*(")/, (_, a, b) => a + d + b);
  html = html.replace(/(<meta name="twitter:url" content=")[^"]*(")/, (_, a, b) => a + canonical + b);

  html = html.replace(/"url": "[^"]*"/, () => `"url": "${canonical}"`);
  html = html.replace(/("description": ")[^"]*(")/, (_, a, b) => a + d + b);
  html = html.replace(/"inLanguage": \[[^\]]*\]/, () => `"inLanguage": ${JSON.stringify(cfg.inLanguage)}`);

  html = html.replace(
    /<body([^>]*)>/,
    `<body$1 data-default-source="${escapeHtml(cfg.defaultSource)}" data-default-target="${escapeHtml(cfg.defaultTarget)}">`
  );

  html = html.replace(
    /(<span class="hero-dot"><\/span>\s*<span>)[^<]*(<\/span>)/,
    (_, a, b) => a + cfg.badge + b
  );
  html = html.replace(
    /(<h1 class="hero-title">)[^<]*(<\/h1>)/,
    (_, a, b) => a + escapeHtml(cfg.h1) + b
  );
  html = html.replace(
    /(<p class="hero-sub">)[^<]*(<\/p>)/,
    (_, a, b) => a + escapeHtml(cfg.subtitle) + b
  );
  html = html.replace(
    /(id="sourceLabelHead">)[^<]*(<\/span>)/,
    (_, a, b) => a + escapeHtml(cfg.sourceLabel) + b
  );
  html = html.replace(
    /(id="targetLabelHead">)[^<]*(<\/span>)/,
    (_, a, b) => a + escapeHtml(cfg.targetLabel) + b
  );

  html = html.replace(
    /(<article id="homeGuide"[^>]*>)[\s\S]*?(<\/article>)/,
    (_, open, close) => `${open}${cfg.guideHtml}${close}`
  );

  // Mark active footer link for the current page
  html = html.replace(
    /(<nav[^>]*id="footerNav"[^>]*>)([\s\S]*?)(<\/nav>)/,
    (_, open, inner, close) => {
      const updated = inner
        .replace(/ class="active"/g, '')
        .replace(`href="${cfg.path}"`, `href="${cfg.path}" class="active"`);
      return open + updated + close;
    }
  );

  return html;
}
